local Logic = require("bscopes_logic")
local F = require("fixtures")

T.test("estados del servidor -> Bookshelf", function()
    T.eq(Logic.mapServerStatus("read"), "finished")
    T.eq(Logic.mapServerStatus("reading"), "reading")
    T.eq(Logic.mapServerStatus("rereading"), "reading")
    T.eq(Logic.mapServerStatus("want_to_read"), "unread")
    T.eq(Logic.mapServerStatus("unread"), "unread")
    T.eq(Logic.mapServerStatus(nil), nil)
    T.eq(Logic.mapServerStatus("otro"), nil)
end)

T.test("estados del sidecar -> Bookshelf", function()
    T.eq(Logic.mapLocalStatus("complete"), "finished")
    T.eq(Logic.mapLocalStatus("reading"), "reading")
    T.eq(Logic.mapLocalStatus("abandoned"), "reading")
    T.eq(Logic.mapLocalStatus(nil), nil)
end)

T.test("progressPercentage del catálogo va de 0 a 100", function()
    T.near(Logic.serverPct(71.83), 0.7183, 1e-9)
    T.eq(Logic.serverPct(nil), nil)
    T.eq(Logic.serverPct(250), 1)
    T.eq(Logic.serverPct(-3), 0)
end)

T.test("progreso: gana el mayor entre servidor y Kindle", function()
    local pct, st = Logic.mergeProgress(0.7183, "reading", 0.40, "reading")
    T.near(pct, 0.7183); T.eq(st, "reading")
    pct, st = Logic.mergeProgress(0.10, "reading", 0.55, "reading")
    T.near(pct, 0.55); T.eq(st, "reading")
end)

T.test("progreso: solo uno de los dos lados", function()
    local pct, st = Logic.mergeProgress(nil, nil, 0.3, nil)
    T.near(pct, 0.3); T.eq(st, "reading")
    pct, st = Logic.mergeProgress(0.2, nil, nil, nil)
    T.near(pct, 0.2); T.eq(st, "reading")
    pct, st = Logic.mergeProgress(nil, "unread", nil, nil)
    T.eq(pct, nil); T.eq(st, "unread")
end)

T.test("estado: terminado en cualquier lado gana", function()
    local _, st = Logic.mergeProgress(0.5, "reading", 1, "finished")
    T.eq(st, "finished")
    _, st = Logic.mergeProgress(1, "finished", 0.2, "reading")
    T.eq(st, "finished")
end)

T.test("fechas ISO del servidor -> Unix (UTC)", function()
    T.eq(Logic.parseIsoTime("2026-10-07T22:38:44.930Z"), 1791412724)
    T.eq(Logic.parseIsoTime("2025-10-06T22:00:15.000Z"), 1759788015)
    T.eq(Logic.parseIsoTime("2000-02-29T00:00:00Z"), 951782400)
    T.eq(Logic.parseIsoTime("1970-01-01T00:00:00Z"), 0)
    T.eq(Logic.parseIsoTime("2026-10-07T22:38:44+02:00"), 1791405524)
    T.eq(Logic.parseIsoTime(nil), nil)
    T.eq(Logic.parseIsoTime("ayer"), nil)
end)

