T.test("buildRecords: campos que pide Bookshelf", function()
    local books = {}
    for id, item in pairs(F.items) do books[tostring(id)] = Logic.normalizeBook(item) end
    local recs = Logic.buildRecords({ 703, 725, 999 }, F.by_book_id, books,
        function(path)
            if path:find("Las Dos Torres") then return 0.40, "reading" end
            if path:find("retorno") then return 0.30, "reading" end
        end,
        function() return true end)
    T.eq(#recs, 2, "999 no está en el Kindle")
    local r = recs[1]
    T.eq(r.filepath, "/mnt/us/documents/Libros/Las Dos Torres.epub")
    T.eq(r.title, "Las Dos Torres")
    T.eq(r.author, "J. R. R. Tolkien")
    T.eq(r.series_name, "El Señor de los Anillos")
    T.eq(r.series_num, "2")
    T.near(r.book_pct, 0.7183, 1e-9, "manda el servidor")
    T.eq(r.percent_finished, r.book_pct)
    T.eq(r.status, "reading"); T.eq(r.read_status, "reading")
    T.eq(r.format, "EPUB")
    T.eq(r.last_read_time, 1791412724)
    T.eq(r.bookorbit_id, 703)
    T.near(recs[2].book_pct, 0.30, 1e-9, "manda el Kindle")
end)

T.test("buildRecords: sin datos del servidor usa el nombre del fichero", function()
    local recs = Logic.buildRecords({ 668 }, F.by_book_id, {}, nil, nil)
    T.eq(recs[1].title, "Africanus. El hijo del cónsul")
    T.eq(recs[1].status, "unread")
    T.eq(recs[1].book_pct, nil)
end)

T.test("buildRecords: ignora ficheros que ya no existen", function()
    local recs = Logic.buildRecords({ 668, 703 }, F.by_book_id, {}, nil,
        function(p) return not p:find("Africanus") end)
    T.eq(#recs, 1)
    T.eq(recs[1].bookorbit_id, 703)
end)

