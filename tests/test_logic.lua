T.test("pertenencia: servidor que IGNORA ids (BookOrbit 3.3.0) -> recorre la scope y cruza", function()
    local server = F.fakeServer({ honor_ids_with_scope = false })
    local ids, info = Logic.collectScopeMembers(server.books, "6", F.local_ids, { page_size = 3 })
    T.same(ids, { 690, 703, 725 })
    T.eq(info.mode, "scan")
    T.eq(info.partial, false)
    -- 8 libros en la scope, de 3 en 3: 3 páginas; ninguna petición repetida por ids.
    T.eq(#server.calls, 3)
    T.eq(server.calls[1].smartScopeId, "6")
    T.eq(server.calls[3].page, 3)
end)

T.test("pertenencia: servidor que APLICA ids -> solo los bloques del Kindle", function()
    local server = F.fakeServer({ honor_ids_with_scope = true })
    local ids, info = Logic.collectScopeMembers(server.books, "6", F.local_ids, { page_size = 4 })
    T.same(ids, { 690, 703, 725 })
    T.eq(info.mode, "ids")
    -- 6 libros en el Kindle en bloques de 4: 2 peticiones.
    T.eq(#server.calls, 2)
    T.eq(server.calls[1].ids, "668,679,690,703")
    T.eq(server.calls[2].ids, "718,725")
end)

T.test("pertenencia: scope sin libros del Kindle", function()
