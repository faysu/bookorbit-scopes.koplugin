T.test("pertenencia: scope que es exactamente el Kindle no hace peticiones de más", function()
    local server = F.fakeServer({ honor_ids_with_scope = false })
    local ids = Logic.collectScopeMembers(server.books, "22", F.local_ids)
    T.same(ids, F.local_ids)
    T.eq(#server.calls, 1)
end)

T.test("pertenencia: scope enorme -> se corta y queda marcada como incompleta", function()
    local server = F.fakeServer({ honor_ids_with_scope = false })
    F.scope_members["99"] = { 1001, 1002, 1003, 1004, 703, 725 }
    local ids, info = Logic.collectScopeMembers(server.books, "99", F.local_ids, { page_size = 2, max_scan_pages = 2 })
    F.scope_members["99"] = nil
    T.eq(info.partial, true)
    T.eq(#server.calls, 2)
    T.same(ids, {})  -- las 4 primeras de la scope no están en el Kindle; 703 y 725 quedan fuera del tope
end)

T.test("pertenencia: error de red -> nil y el error", function()
